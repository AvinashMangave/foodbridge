const mongoose = require('mongoose');
const { createAdaptiveModel } = require('./modelFactory');

const notificationSchema = new mongoose.Schema({
  recipient: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true
  },
  sender: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    default: null
  },
  title: {
    type: String,
    required: true
  },
  message: {
    type: String,
    required: true
  },
  type: {
    type: String,
    enum: [
      'donation_new',
      'request_received',
      'request_approved',
      'request_rejected',
      'status_update',
      'expiry_alert',
      'system'
    ],
    default: 'system'
  },
  link: {
    type: String,
    default: ''
  },
  isRead: {
    type: Boolean,
    default: false
  },
  createdAt: {
    type: Date,
    default: Date.now
  }
});

module.exports = createAdaptiveModel('Notification', notificationSchema, 'notifications');
